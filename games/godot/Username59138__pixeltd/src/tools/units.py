def sym(half):
    return [r + r[:-1][::-1] for r in half]


def put(rows, x, y, patch):
    rows = list(rows)
    need = x + max(len(pr) for pr in patch)
    if need > len(rows[0]):   # grow the canvas to the right so the overlay fits
        rows = [r + '.' * (need - len(r)) for r in rows]
    for dy, pr in enumerate(patch):
        r = list(rows[y + dy])
        for dx, ch in enumerate(pr):
            if ch != '.':
                r[x + dx] = ch
        rows[y + dy] = ''.join(r)
    return rows


def render(rows, cmap):
    return make(rows, {k: P[v] if isinstance(v, str) else v for k, v in cmap.items()})


