local ADV = 5.6   -- monospaced advance in grid units (glyph is 4 wide)

local byByte = {}
for ch, strokes in pairs(GLYPHS) do byByte[ch:byte()] = strokes end

-- Scratch buffers keyed by length, so drawing allocates nothing.
local bufs = {}
local function getbuf(n)
  local b = bufs[n]
  if not b then b = {}; bufs[n] = b end
  return b
end

function F.advance(h) return ADV * h / 6 end

function F.width(text, h)
  local n = #text
  if n == 0 then return 0 end
  return ((n - 1) * ADV + 4) * h / 6
end

-- Draw text with its cap line at y. align: nil/"left", "center", "right".
function F.draw(text, x, y, h, align)
  text = string.upper(tostring(text))
  local s = h / 6
  if align == "center" then
    x = x - F.width(text, h) / 2
  elseif align == "right" then
    x = x - F.width(text, h)
  end
  local adv = ADV * s
  for i = 1, #text do
    local g = byByte[text:byte(i)]
    if g then
      for k = 1, #g do
        local pl = g[k]
        local n = #pl
        local b = getbuf(n)
        for j = 1, n, 2 do
          b[j] = x + pl[j] * s
          b[j + 1] = y + pl[j + 1] * s
        end
        lg.line(b)
      end
    end
    x = x + adv
  end
end

return F
