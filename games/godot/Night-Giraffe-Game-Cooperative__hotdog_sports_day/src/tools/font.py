SPACE = 3
CHARS = sorted(G)


def width_of(text, scale=1):
    w = 0
    for i, ch in enumerate(text):
        if ch == " ":
            w += SPACE * scale
        elif ch in G:
            w += (len(G[ch][0]) + 1) * scale
    return max(0, w - scale)


def draw(img, text, x, y, color, scale=1, shadow=None):
    """Letter `text` onto a PIL image with its capital tops at y."""
    px = img.load()
    for pass_, col, off in ((0, shadow, 1), (1, color, 0)):
        if col is None:
            continue
        cx = x
        for ch in text:
            if ch == " ":
                cx += SPACE * scale
                continue
            rows = G.get(ch)
            if rows is None:
                continue
            for r, row in enumerate(rows):
                for c, v in enumerate(row):
                    if v != "#":
                        continue
                    for dy in range(scale):
                        for dx in range(scale):
                            X, Y = cx + c * scale + dx + off * scale, y + r * scale + dy + off * scale
                            if 0 <= X < img.width and 0 <= Y < img.height:
                                px[X, Y] = tuple(col) + ((255,) if len(col) == 3 else ())
            cx += (len(rows[0]) + 1) * scale


def write_bmfont(out_dir, name, scale=1, mode="solid"):
    """Writes <name>.fnt and <name>.png: every glyph in white, for Godot to tint."""
    pitch = scale if mode == "solid" else 2 * scale // 2 if False else scale
    cells = []
    for ch in CHARS:
        rows = G[ch]
        w, h = len(rows[0]), len(rows)
        if mode == "led":
            gw, gh = w * 2 - 1, h * 2 - 1
        else:
            gw, gh = w * scale, h * scale
        cells.append((ch, rows, gw, gh))
    W = 256
    x = y = 1
    rowh = 0
    placed = []
    for ch, rows, gw, gh in cells:
        if x + gw + 1 > W:
            x, y, rowh = 1, y + rowh + 1, 0
        placed.append((ch, rows, gw, gh, x, y))
        x += gw + 1
        rowh = max(rowh, gh)
    H = 1
    while H < y + rowh + 1:
        H *= 2
    img = np.zeros((H, W, 4), np.uint8)
    for ch, rows, gw, gh, gx, gy in placed:
        for r, row in enumerate(rows):
            for c, v in enumerate(row):
                if v != "#":
                    continue
                if mode == "led":
                    img[gy + r * 2, gx + c * 2] = (255, 255, 255, 255)
                else:
                    img[gy + r * scale:gy + (r + 1) * scale, gx + c * scale:gx + (c + 1) * scale] = (255, 255, 255, 255)
    k = 2 if mode == "led" else scale
    line_h = 11 * k
    base = 7 * k
    lines = [
        f'info face="HotDog {name}" size={9 * k} bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 '
        f'padding=0,0,0,0 spacing=1,1 outline=0',
        f"common lineHeight={line_h} base={base} scaleW={W} scaleH={H} pages=1 packed=0",
        f'page id=0 file="{name}.png"',
        f"chars count={len(placed) + 1}",
        f"char id=32 x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 xadvance={SPACE * k} page=0 chnl=15",
    ]
    for ch, rows, gw, gh, gx, gy in placed:
        adv = (len(rows[0]) + 1) * k
        lines.append(f"char id={ord(ch)} x={gx} y={gy} width={gw} height={gh} xoffset=0 yoffset=0 "
                     f"xadvance={adv} page=0 chnl=15")
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / f"{name}.fnt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    Image.fromarray(img).save(out_dir / f"{name}.png")
    return len(placed)


