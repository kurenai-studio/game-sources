# ------------------------------------------------------------------ sound effects

def sweep(f0, f1, length, wave_fn="square", curve=1.0, duty=0.5):
    n = int(length * SR)
    t = np.arange(n) / SR
    k = (t / length) ** curve
    f = f0 * (f1 / f0) ** k
    ph = np.cumsum(f) / SR
    if wave_fn == "square":
        return np.where(ph % 1.0 < duty, 1.0, -1.0)
    if wave_fn == "tri":
        return 4.0 * np.abs(ph % 1.0 - 0.5) - 1.0
    return np.sin(2 * np.pi * ph)


def make_fx():
    """Soft-edged sounds: sines, triangles and FM through a low-pass, with a
    short room on each, so nothing bites even played over and over."""
    os.makedirs(os.path.join(ROOT, "fx"), exist_ok=True)
    rng = np.random.default_rng(7)

    def sine_sweep(f0, f1, length, curve=1.0):
        return sweep(f0, f1, length, "sine", curve)

    def soft(x, cut=3500, room=0.12):
        x = lowpass(np.concatenate([x, np.zeros(int(0.25 * SR))]), cut)
        return reverb(x, room)

    fx = {}
    # 乾坤挪移: a quick rising swish, then a bell-like pop on the other side
    n = int(0.14 * SR)
    swish = sine_sweep(400, 1600, 0.14) * env(n, a=0.01, r=0.04) * 0.6 + lowpass(noise(n, rng), 2500) * np.linspace(0, 0.4, n)
    fx["blink"] = soft(np.concatenate([swish, epiano(88, 0.35) * 0.8]))
    # 斗转星移: a warm wobble that dips and turns back up
    n = int(0.5 * SR)
    t = np.arange(n) / SR
    f = 520 - 260 * np.sin(np.pi * t / 0.5) + 25 * np.sin(2 * np.pi * 9 * t)
    ph = np.cumsum(f) / SR
    fx["flip"] = soft((4.0 * np.abs(ph % 1.0 - 0.5) - 1.0) * env(n, a=0.02, d=0.25, s=0.6, r=0.1), 2200)
    # 重力转移: a falling tone settling into a deep thud
    fall = sine_sweep(700, 90, 0.42, curve=0.6) * env(int(0.42 * SR), a=0.01, r=0.03)
    fx["gravity"] = soft(np.concatenate([fall, kick(0.35) * 1.3]), 1800)
    # 视角转移: a muffled, wobbling stutter
    parts = []
    for i in range(6):
        m = int(0.045 * SR)
        f0 = rng.choice([260, 330, 390, 520])
        tt = np.arange(m) / SR
        parts.append(np.sin(2 * np.pi * f0 * tt + 2.0 * np.sin(2 * np.pi * f0 * 1.5 * tt)) * env(m, a=0.004, r=0.015) * (0.7 if i % 2 else 1.0))
    fx["view"] = soft(np.concatenate(parts), 2400)
    # any other skill: a short rising electric-piano arpeggio
    fx["cast"] = soft(np.concatenate([epiano(n, 0.07) for n in (72, 76, 79)] + [epiano(84, 0.3)]))
    # 规则转移 SHIFT!: a filtered rise into a warm chord
    n = int(0.4 * SR)
    rise = lowpass(noise(n, rng), 1800) * np.linspace(0.05, 0.6, n) + sine_sweep(180, 720, 0.4) * np.linspace(0.1, 0.5, n)
    chord = sum(pad_voice(m, 0.7, rng) for m in (57, 64, 69, 72)) / 3.0 + sum(epiano(m, 0.7) for m in (69, 76)) * 0.3
    fx["shift"] = soft(np.concatenate([rise, chord + np.pad(kick(0.35), (0, int(0.35 * SR))) * 0.7]), 2800, 0.2)
    # menu click: a tiny wooden tick
    fx["click"] = lowpass(np.sin(2 * np.pi * 1300 * np.arange(int(0.03 * SR)) / SR) * np.exp(-np.arange(int(0.03 * SR)) / SR * 120), 3000)
    # end of a match: a bright and a falling phrase on the electric piano
    fx["win"] = soft(np.concatenate([epiano(n, 0.12) for n in (72, 76, 79)] + [epiano(84, 0.8)]))
    fx["lose"] = soft(np.concatenate([epiano(n, 0.18) for n in (67, 64, 60)] + [epiano(55, 0.8)]), 2500)
    for k, x in fx.items():
        x = x / (np.max(np.abs(x)) + 1e-9) * 0.8
        write_wav(os.path.join(ROOT, "fx", k + ".wav"), x)


