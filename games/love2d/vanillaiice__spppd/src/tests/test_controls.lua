local h = require("tests/harness")
local input = require("src/input")
local settings = require("src/settings")
local menu = require("src/menu")

-- Back to the defaults, with nothing held, whatever a test did.
local function fresh()
  input.setBindings()
  input.clear()
  menu.cancelCapture()
end

local function keyAction(key)
  input.clear()
  input.press(key)
  for _, action in ipairs(input.ACTIONS) do
    if input.consume(action) then return action end
  end
  return nil
end

h.describe("controls", function()
  h.it("the defaults are the keys and buttons the game always had", function()
    fresh()
    h.assertEq(table.concat(input.binds.throttle, " "), "w up")
    h.assertEq(table.concat(input.binds.pause, " "), "p escape")
    h.assertEq(table.concat(input.binds.handbrake, " "), "lshift rshift")
    h.assertEq(input.pads.handbrake[1], "rightshoulder")
    h.assertEq(input.pads.boost[1], "leftshoulder")
    h.assertEq(#input.pads.throttle, 0, "the trigger is gas until a button is set")
    h.assertEq(next(input.keyChanges()), nil)
    h.assertEq(next(input.buttonChanges()), nil)
    h.assertTrue(input.setBindings(), "the defaults are valid")
  end)

  h.it("a key taken from another action swaps with it", function()
    fresh()
    h.assertTrue(input.rebindKey("boost", "w"))
    h.assertEq(keyAction("w"), "boost")
    h.assertEq(keyAction("space"), "throttle")
    h.assertEq(keyAction("up"), "throttle", "the arrow stays")
    local changes = input.keyChanges()
    h.assertEq(changes.boost, "w")
    h.assertEq(changes.throttle, "space")
    -- What's saved brings the same keys back.
    input.setBindings()
    h.assertTrue(input.setBindings(changes, nil))
    h.assertEq(input.keyFor("boost"), "w")
    h.assertEq(input.keyFor("throttle"), "space")
    input.resetKeys()
    h.assertEq(input.keyFor("boost"), "space")
    fresh()
  end)

  h.it("a key nobody had just moves, and the old one does nothing", function()
    fresh()
    h.assertTrue(input.rebindKey("horn", "j"))
    h.assertEq(keyAction("j"), "horn")
    h.assertEq(keyAction("h"), nil)
    fresh()
  end)

  h.it("the arrows, right shift and Esc can't be taken", function()
    fresh()
    for _, key in ipairs({ "up", "down", "left", "right", "rshift", "escape" }) do
      h.assertTrue(not input.rebindKey("boost", key), key)
    end
    h.assertEq(input.keyFor("boost"), "space")
  end)

  h.it("saved keys that clash or make no sense fall back to the defaults", function()
    fresh()
    h.assertTrue(not input.setBindings({ boost = "w" }, nil), "w would do two things")
    h.assertEq(input.keyFor("boost"), "space")
    h.assertEq(input.keyFor("throttle"), "w")
    h.assertTrue(not input.setBindings({ boost = "up" }, nil))
    h.assertTrue(not input.setBindings({ boost = 7 }, nil))
    h.assertTrue(not input.setBindings(nil, { horn = "guide" }))
    h.assertTrue(not input.setBindings(nil, { pause = false }), "pause keeps a button")
    h.assertEq(input.buttonFor("pause"), "start")
    fresh()
  end)

  h.it("a pad button can be gas, and the action that had it is left without", function()
    fresh()
    h.assertTrue(input.rebindButton("throttle", "a"))
    h.assertEq(input.buttonFor("shiftDown"), nil)
    input.gamepadPress(nil, "a")
    h.assertTrue(input.isDown("throttle"))
    h.assertEq(input.throttle(), 1)
    h.assertTrue(not input.consume("shiftDown"))
    input.gamepadRelease(nil, "a")
    local changes = input.buttonChanges()
    h.assertEq(changes.throttle, "a")
    h.assertEq(changes.shiftDown, false)
    -- false survives a save.
    local loaded = assert(loadstring("return " .. settings.serialize(changes)))()
    input.setBindings()
    h.assertTrue(input.setBindings(nil, loaded))
    h.assertEq(input.buttonFor("throttle"), "a")
    h.assertEq(input.buttonFor("shiftDown"), nil)
    input.resetButtons()
    h.assertEq(input.buttonFor("shiftDown"), "a")
    fresh()
  end)

  h.it("pause always keeps a pad button, and the guide button isn't offered", function()
    fresh()
    local ok, why = input.rebindButton("throttle", "start")
    h.assertTrue(not ok)
    h.assertEq(why, "pause")
    h.assertTrue(input.rebindButton("horn", "start"), "a swap is fine")
    h.assertEq(input.buttonFor("pause"), "b")
    h.assertTrue(not input.rebindButton("boost", "guide"))
    fresh()
  end)

  h.it("the on-screen controls work whatever keys are set", function()
    fresh()
    input.rebindKey("boost", "w")
    input.press("touch:boost")
    h.assertTrue(input.isDown("boost"))
    h.assertTrue(not input.isDown("throttle"))
    input.release("touch:boost")
    h.assertTrue(not input.isDown("boost"))
    fresh()
  end)

  h.it("two drivers both follow the changed keys and buttons", function()
    fresh()
    input.rebindKey("handbrake", "k")
    input.rebindButton("boost", "y")
    local keys, pad = input.reader(true, nil), input.reader(false, "pad2")
    input.press("k")
    h.assertTrue(keys:isDown("handbrake"))
    input.gamepadPress("pad2", "y")
    h.assertTrue(pad:consume("boost"))
    h.assertTrue(not pad:consume("respawn"), "y isn't reset any more")
    fresh()
  end)

  h.it("a waiting row takes the next key and saves it", function()
    fresh()
    local savedKeys = settings.keys
    menu.go("keys")
    h.assertTrue(not menu.takeKey("b"), "nothing waits until a row is picked")
    menu.startCapture("key", "horn")
    h.assertTrue(menu.takeKey("b"))
    h.assertTrue(menu.textTaken(), "the letter isn't typed as a cheat too")
    h.assertEq(input.keyFor("horn"), "b")
    h.assertEq(settings.keys.horn, "b")
    h.assertTrue(not menu.capturing())
    -- Esc lets go without changing anything.
    menu.startCapture("key", "horn")
    h.assertTrue(menu.takeKey("escape"))
    h.assertEq(input.keyFor("horn"), "b")
    -- A fixed key is refused, and the row lets go.
    menu.startCapture("key", "horn")
    h.assertTrue(menu.takeKey("up"))
    h.assertEq(input.keyFor("horn"), "b")
    h.assertTrue(not menu.capturing())
    -- A pad press lets go of a keyboard row.
    menu.startCapture("key", "horn")
    h.assertTrue(menu.takeButton("a"))
    h.assertTrue(not menu.capturing())
    h.assertEq(input.buttonFor("shiftDown"), "a")
    settings.keys = savedKeys
    settings.save()
    fresh()
    menu.go("main")
  end)

  h.it("a waiting pad row takes the next button and ignores keys", function()
    fresh()
    local savedButtons = settings.padButtons
    local gamepads = input.gamepads
    input.gamepads = function() return { "pad" } end
    menu.go("pad")
    menu.startCapture("pad", "horn")
    h.assertTrue(menu.takeKey("k"), "a key is swallowed")
    h.assertTrue(menu.capturing(), "and the row still waits")
    h.assertTrue(menu.takeButton("rightstick"))
    h.assertEq(input.buttonFor("horn"), "rightstick")
    h.assertEq(settings.padButtons.horn, "rightstick")
    input.gamepads = function() return {} end
    menu.startCapture("pad", "horn")
    h.assertTrue(not menu.capturing(), "no pad, nothing to wait for")
    input.gamepads = gamepads
    settings.padButtons = savedButtons
    settings.save()
    fresh()
    menu.go("main")
  end)

  h.it("keys and buttons have names a player knows", function()
    h.assertEq(menu.keyName("lshift"), "L SHIFT")
    h.assertEq(menu.keyName("kp5"), "NUM 5")
    h.assertEq(menu.keyName("w"), "W")
    h.assertEq(menu.buttonName("a", 1), "CROSS")
    h.assertEq(menu.buttonName("a", 2), "A")
    h.assertEq(menu.buttonName("a", nil), "CROSS/A")
    h.assertEq(menu.buttonName("throttle", 1), "R2")
    h.assertEq(menu.buttonName("dpright", 2), "D-PAD RIGHT")
  end)
end)
