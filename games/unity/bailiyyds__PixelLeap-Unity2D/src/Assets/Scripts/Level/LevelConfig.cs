    /// <summary>
    /// 数据驱动关卡：用字符画描述关卡布局，策划改文本即可出新关，不需要动场景和代码。
    ///   #  地面      ^  尖刺      P  出生点
    ///   W  冲撞虫    J  跳跃虫    S  射手虫
    ///   C  检查点    G  终点      .  空
    /// 第一行是关卡最上方。
    /// </summary>
    [CreateAssetMenu(menuName = "PixelLeap/Level Config", fileName = "Level")]
    public class LevelConfig : ScriptableObject
    {
        public string displayName = "新关卡";
        public Color background = new Color(0.08f, 0.1f, 0.16f);
        public Color groundColor = new Color(0.3f, 0.42f, 0.55f);
        [TextArea(8, 30)] public string layout;

        public string[] Rows => (layout ?? "").Replace("\r", "").Trim('\n').Split('\n');

        public static LevelConfig Create(string name, Color bg, Color ground, string layout)
        {
            var c = CreateInstance<LevelConfig>();
            c.displayName = name; c.background = bg; c.groundColor = ground; c.layout = layout;
            return c;
        }

