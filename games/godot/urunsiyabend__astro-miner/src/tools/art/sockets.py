"""Measure how each colony sprite stands on a build site and write scripts/ui/ColonySockets.gd.
Run it again whenever a colony sprite is replaced:

    python3 tools/art/sockets.py

The colony is a 2:1 isometric grid of build sites joined by paths (drawn in ColonyView).
A building stands on its site by its FOOT: the centre of its base footprint. In 2:1 iso a
footprint diamond w wide is w/2 tall, so its centre is w/4 above its lowest point; the base is
the widest part of the sprite's lower half. FOOT and BASE_W are measured from the alpha, never
eyeballed. Check with ASTRO_SITES=1 (DevShot), which draws every site and foot.
"""
import os

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
COL = os.path.join(ROOT, "assets", "colony")
OUT = os.path.join(ROOT, "scripts", "ui", "ColonySockets.gd")
SPRITES = ["dome", "power", "workshop", "lab", "pad", "teleporter"]

PATHS = os.path.join(COL, "paths.png")


def erode(m, r):
	"""Binary erosion by a (2r+1) square, with shifted ANDs (no scipy)."""
	out = m.copy()
	for dy in range(-r, r + 1, max(1, r // 3)):
		for dx in range(-r, r + 1, max(1, r // 3)):
			out &= np.roll(np.roll(m, dy, 0), dx, 1)
	return out


def components(m):
	"""Bounding boxes of the connected blobs of m (4-neighbour flood fill)."""
	from collections import deque
	h, w = m.shape
	seen = np.zeros_like(m)
	out = []
	for y, x in zip(*np.where(m)):
		if seen[y, x]:
			continue
		q, ys, xs = deque([(y, x)]), [], []
		seen[y, x] = True
		while q:
			cy, cx = q.popleft()
			ys.append(cy); xs.append(cx)
			for ny, nx in ((cy + 1, cx), (cy - 1, cx), (cy, cx + 1), (cy, cx - 1)):
				if 0 <= ny < h and 0 <= nx < w and m[ny, nx] and not seen[ny, nx]:
					seen[ny, nx] = True
					q.append((ny, nx))
		out.append((min(xs), min(ys), max(xs), max(ys), len(xs)))
	return out


PLOT_ASPECT = 2.0


def sites():
	"""The dirt plots of the paths layer (its own sprite over the sky background): the dirt is one X (four plots on the
	diagonals joined to a round hub by paths). Eroding it removes the thin paths, leaving five
	blobs; the biggest is the hub, the others are named by their quadrant around it."""
	a = np.asarray(Image.open(PATHS).convert("RGBA")).astype(float)
	dirt = a[..., 3] > 200
	small = dirt[::2, ::2]
	core = erode(small, 18)
	blobs = [c for c in components(core) if c[4] > 400]
	blobs.sort(key=lambda c: -c[4])
	def grow(c):
		# back to the full blob: the eroded box grown by the erosion radius, in full pixels
		return ((c[0] + c[2]) / 2 * 2, (c[1] + c[3]) / 2 * 2, (c[2] - c[0] + 36) * 2)
	hub = grow(blobs[0])
	out = {"hub": hub}
	# the plots' own diamond proportion (width / height), for outlines drawn on them
	global PLOT_ASPECT
	PLOT_ASPECT = float(np.mean([(c[2] - c[0]) / max(1, c[3] - c[1]) for c in blobs[1:5]]))
	for c in blobs[1:5]:
		x, y, w = grow(c)
		name = ("power" if x < hub[0] else "workshop") if y < hub[1] else ("teleporter" if x < hub[0] else "lab")
		out[name] = (x, y, w)
	# the robot's landing pad stands on the plain ground above the colony, centred over the
	# two upper plots; the bottom stays clear
	top = (out["power"][1] + out["workshop"][1]) / 2.0
	out["pad"] = (hub[0], top - out["power"][2] * 0.5, out["power"][2] * 1.15)
	return out, a.shape[1], a.shape[0]


def foot(name):
	a = np.asarray(Image.open(os.path.join(COL, name + ".png")).convert("RGBA"))[..., 3]
	h, w = a.shape
	ys, xs = np.where(a > 200)
	y_low = ys.max()
	lower = ys > ys.min() + (y_low - ys.min()) * 0.5
	x0, x1 = xs[lower].min(), xs[lower].max()
	bw = x1 - x0
	return ((x0 + x1) / 2.0 / w, (y_low - bw / 4.0) / h, bw / w)


def main():
	found, bw_, bh_ = sites()
	lines = ["class_name ColonySockets", "extends RefCounted", "",
		"## GENERATED by tools/art/sockets.py from the colony art; do not edit by hand.", "",
		"## assets/colony/paths.png (%dx%d): each site's centre and width, in its pixels: the dirt" % (bw_, bh_),
		"## plots found in the art (the hub is the round middle), the decorations' free spots.",
		"const SITES := {"]
	for k in ["hub", "power", "workshop", "lab", "teleporter", "pad"]:
		x, y, wd = found[k]
		lines.append('\t"%s": Vector3(%.1f, %.1f, %.1f),' % (k, x, y, wd))
	lines += ["}", "", "## A plot's diamond is this many times wider than tall (measured on the art).",
		"const PLOT_ASPECT := %.3f" % PLOT_ASPECT, "",
		"## Each sprite's foot (centre of its base footprint) and base width, as fractions of its",
		"## square canvas.", "const FOOT := {"]
	widths = []
	for n in SPRITES:
		fx, fy, bw = foot(n)
		lines.append('\t"%s": Vector2(%.4f, %.4f),' % (n, fx, fy))
		widths.append('\t"%s": %.4f,' % (n, bw))
	lines += ["}", "const BASE_W := {"] + widths + ["}", ""]
	open(OUT, "w").write("\n".join(lines))
	print("\n".join(lines))


main()
