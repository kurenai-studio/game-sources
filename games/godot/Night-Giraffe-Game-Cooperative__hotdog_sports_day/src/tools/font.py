"""The game's lettering: one hand-drawn pixel alphabet, written out as bitmap
fonts Godot loads (BMFont .fnt + .png) and usable from Python to letter the
stadium's boards.

Every glyph is 9 rows: rows 0-6 are the capital height (7 pixels), the
x-height is 5, and rows 7-8 are the descenders. Letters are 1 to 5 pixels
wide, with a pixel between letters. Digits are all 5 wide so times line up.

Three faces come from the one alphabet:
  small  as drawn (7 px capitals) for nearly everything
  big    every pixel doubled (14 px capitals) for titles and results
  led    every pixel a dot with a gap (the stadium scoreboard's lights)
"""
