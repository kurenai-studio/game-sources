t=0
color=12
playing=false
finalScore=5

player={}

function player:new()
	newObj={
		w=2,
		h=16,
		dy=0, --momentum
		sc=0 --score
	}
	self.__index=self
	return setmetatable(newObj,self)
end

function player:setAttributes(x,y,id)
	self.x=x
	self.y=y
	self.id=id
end

function player:move()
	local up
	local down
	if self.id=="p1" then
		up=btn(6)
		down=btn(4)
	else
		up=btn(0)
		down=btn(1)
	end
	
	if up then
		if self.y>0 then
			self.y=self.y-1
			self.dy=-1
		end
	elseif down then
	 if self.y<120 then
			self.y=self.y+1
			self.dy=1
		end
	else
		self.dy=0
	end
	
end

p1=player:new()
p1:setAttributes(10,60,"p1")

p2=player:new()
p2:setAttributes(228,60,"p2")

local d={-1,1}
b={
	x=120,
	y=68,
	r=2,
	dx=d[math.random(1,2)],
	dy=d[math.random(1,2)],
	hit=false,
	scored=false,
	-- Avoid collision with player multiple times per second
	dtime=time()
}

function b:reset(scored)
	b.x=120
	b.y=68
	b.dx=nil
	b.dy=nil
	b.hit=false
	b.scored=false
	
	if scored=="p1" then
		b.dx=1
	else
		b.dx=-1
	end
	b.dy=d[math.random(1,2)]
end
	
function b:move()
	-- Check collision with borders
	if self.y<0+self.r or self.y>135-self.r then
		self.dy=self.dy*-1
	end
	
	local left=pix(self.x-self.r-1,self.y)==color
	local right=pix(self.x+self.r+1,self.y)==color
	local top=pix(self.y-self.r-1,self.x)==color
	local bottom=pix(self.y+self.r+1,self.x)==color
	
	if self.dx<0 and self.x<=p1.x+self.r+1
	or self.dx>0 and self.x>=p2.x-self.r-1 then
		if left or right or top or bottom then
			--Change momentum
			if self.dx<0 then
				if p1.dy~=self.dy and p1.dy~=0 then
					self.dy=self.dy*-1
				end
			elseif self.dx>0 then
				if p2.dy~=self.dy and p2.dy~=0 then
					self.dy=self.dy*-1
				end
			end
			-- Increase speed after first hit
			if not self.hit then
				self.hit=true
				self.dx=self.dx*2
			end
			
			self.dx=self.dx*-1
			sfx(1,"D-5",5)
		end
	end
	
	self.x=self.x+self.dx
	self.y=self.y+self.dy
end

function b:score()
	if self.x<0 then
		if not b.scored then
			p2.sc=p2.sc+1
			b.scored=true
			sfx(2,"D-5",60)
		end
		if delay(90) then
			b:reset("p2")
			counter:reset()
		end
	end
	if self.x>239 then
		if not b.scored then
			p1.sc=p1.sc+1
			b.scored=true
			sfx(2,"D-5",60)
		end
		if delay(90) then
			b:reset("p1")
			counter:reset()
		end
	end
end

counter={
	ready=false,
	num=3
}

function counter:down()
	if self.num>0 then
		if t%60==0 then
			sfx(0,"C-5",15)
			self.num=self.num-1
		end
	elseif self.num==0 then
		if t%60==0 then
			sfx(0,"C-6",30)
			self.ready=true
		end
	end
end

function counter:reset()
	self.ready=false
	self.num=3
end

function TIC()
	draw()
	update()
	t=t+1
end

function draw()
	cls()
	-- Title screen
	if p1.sc==0 and p2.sc==0 and not playing then
		spr(256+t%60//30*32,56,20,0,2,0,0,8,2)
		print("Press C to start",76,68,color)
	elseif counter.num>0 then
		print(counter.num,120,68,color)
	end
	
	rect(p1.x, p1.y, p1.w, p1.h, color)
	rect(p2.x, p2.y, p2.w, p2.h, color)
	line(0,0,239,0,14)
	line(0,135,239,135,14)
	if playing and counter.ready then
		circ(b.x, b.y, b.r, color)
	end
	if playing then
		print(p1.sc,60,15,color,true)
		print(p2.sc,174,15,color,true)
	end
	if not playing and p1.sc==finalScore or p2.sc==finalScore then
		local winner
		if p1.sc>p2.sc then
			winner="P1"
		else
			winner="P2"
		end
		print(winner .. " wins!", 100, 68, color)
	end
end

function update()
	if playing then
		p1:move()
		p2:move()
	end
	if playing and counter.ready then
		b:move()
		b:score()
	end
	if playing and not counter.ready then
		counter:down()
	elseif btn(5) then
		playing=true
	end
	if p1.sc==finalScore or p2.sc==finalScore then
		playing=false
		if delay(240) then
			reset()
		end
	end
end

t2=0
function delay(frames)
	t2=t2+1
	if t2%frames==0 then
		t2=0
		return true
	end
end
