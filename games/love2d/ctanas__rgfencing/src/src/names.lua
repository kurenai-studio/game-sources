local function words(s)
  local t = {}
  for w in s:gmatch("%S+") do t[#t + 1] = w end
  return t
end

N.CODES = {}
local LISTS = {}
for code, names in pairs(DATA) do
  N.CODES[#N.CODES + 1] = code
  LISTS[code] = words(names)
end
table.sort(N.CODES)
for code, names in pairs(HOME) do LISTS[code] = words(names) end

