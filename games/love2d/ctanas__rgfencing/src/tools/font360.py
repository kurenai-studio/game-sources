# accents (3 rows above the cap line; the last is a gap)
A7 = {"grave": ["..#....", "...#...", "......."], "acute": ["....#..", "...#...", "......."],
      "circ": ["...#...", "..#.#..", "......."], "uml": [".......", "..#.#..", "......."],
      "ring": ["..###..", "..#.#..", "..###.."], "breve": [".#...#.", "..###..", "......."],
      "caron": ["..#.#..", "...#...", "......."], "dacute": ["...#.#.", "..#.#..", "......."],
      "tilde": ["..##..#", ".#..##.", "......."]}
A5 = {"grave": [".#...", "..#..", "....."], "acute": ["...#.", "..#..", "....."],
      "circ": ["..#..", ".#.#.", "....."], "uml": [".....", ".#.#.", "....."]}
BELOW = {"cedil": ["...#...", "....#..", "..##..."], "comma": ["...##..", "....#..", "...#..."]}
GEN = {"À": ("A", "grave"), "Á": ("A", "acute"), "Â": ("A", "circ"), "Ä": ("A", "uml"), "Å": ("A", "ring"),
       "Ă": ("A", "breve"), "Ã": ("A", "tilde"), "È": ("E", "grave"), "É": ("E", "acute"), "Ê": ("E", "circ"),
       "Ë": ("E", "uml"), "Ě": ("E", "caron"), "Ì": ("I", "grave"), "Í": ("I", "acute"), "Î": ("I", "circ"),
       "Ï": ("I", "uml"), "Ò": ("O", "grave"), "Ó": ("O", "acute"), "Ô": ("O", "circ"), "Ö": ("O", "uml"),
       "Õ": ("O", "tilde"), "Ő": ("O", "dacute"), "Ù": ("U", "grave"), "Ú": ("U", "acute"), "Û": ("U", "circ"),
       "Ü": ("U", "uml"), "Ű": ("U", "dacute"), "Ů": ("U", "ring"), "Ñ": ("N", "tilde"), "Ń": ("N", "acute"),
       "Ň": ("N", "caron"), "Ý": ("Y", "acute"), "Ć": ("C", "acute"), "Č": ("C", "caron"), "Š": ("S", "caron"),
       "Ś": ("S", "acute"), "Ž": ("Z", "caron"), "Ź": ("Z", "acute"), "Ř": ("R", "caron"), "Ď": ("D", "caron"),
       "Ť": ("T", "caron"), "Ç": ("C", None, "cedil"), "Ș": ("S", None, "comma"), "Ț": ("T", None, "comma"),
       "Ş": ("S", None, "cedil")}
out = {}
for ch, rows in G.items():
    out[ch] = "/".join(rows)
for ch, spec in GEN.items():
    base = G[spec[0]]
    w = len(base[0])
    if spec[1]:
        acc = (A5 if w == 5 else A7)[spec[1]]
        out[ch] = "!" + "/".join(acc + base)
    else:
        out[ch] = "/".join(base + BELOW[spec[2]])
# lowercase accented: the accent sits in the 3 empty rows above the x-height
L6 = {"grave": ["..#...", "...#..", "......"], "acute": ["...#..", "..#...", "......"],
      "circ": ["..##..", ".#..#.", "......"]}
for ch, (b, a) in {"é": ("e", "acute"), "è": ("e", "grave"), "ê": ("e", "circ"), "à": ("a", "grave")}.items():
    base = G[b]
    out[ch] = "/".join(L6[a] + base[3:])
# Romanian lowercase: ă â î ș ț
L6["breve"] = [".#..#.", "..##..", "......"]
for ch, (b, a) in {"ă": ("a", "breve"), "â": ("a", "circ")}.items():
    out[ch] = "/".join(L6[a] + G[b][3:])
out["î"] = "/".join([".#.", "#.#", "..."] + G["i"][3:])
out["ș"] = "/".join(G["s"] + ["..##..", "...#..", "..#..."])
out["ț"] = "/".join(G["t"] + ["..##.", "...#.", "..#.."])
for ch, v in out.items():
    rows = v.lstrip("!").split("/")
    assert all(len(r) == len(rows[0]) for r in rows), ch
    start = 0 if v.startswith("!") else 3
    assert start + len(rows) <= 16, (ch, start + len(rows))
lines = ["-- The 7x10 pixel font used at 360x240 (and doubled at 720x480).",
         "-- Generated from pixel grids; accented letters are base + mark.",
         "-- Rows start at the cap line (row 3 of 16) unless prefixed with \"!\".", "", "return {"]
for ch in sorted(out):
    key = ch.replace("\\", "\\\\").replace('"', '\\"')
    lines.append('  ["%s"] = "%s",' % (key, out[ch]))
lines.append("}")
open(sys.argv[1], "w").write("\n".join(lines) + "\n")
print(len(out), "glyphs")
