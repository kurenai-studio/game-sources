local function roll(rng, a, b)
  if rng then return rng:random(a, b) end
  return love.math.random(a, b)
end

-- A random fencer: { last = name, nation = code }. `used` (optional) is a
-- set of names to avoid; rng (optional) a love RandomGenerator.
function N.random(_, rng, used)
  for _ = 1, 30 do
    local code = N.CODES[roll(rng, 1, #N.CODES)]
    local L = LISTS[code]
    local name = L[roll(rng, 1, #L)]
    if not used or not used[name] then
      if used then used[name] = true end
      return { last = name, nation = code }
    end
  end
  return { last = "DOE", nation = "USA" }
end

-- Whether there are names for this nation.
function N.has(code) return LISTS[code] ~= nil end

-- A fencer from one nation. Once every name in its list is taken, a name
-- comes back with an initial, as on a results sheet: "ROSSI M.".
local INITIALS = "ABCDEFGHIJKLMNOPRSTVZ"
function N.from(code, used, rng)
  local L = LISTS[code]
  if not L then return N.random(nil, rng, used) end
  used = used or {}
  local free = {}
  for _, name in ipairs(L) do
    if not used[name] then free[#free + 1] = name end
  end
  local name
  if #free > 0 then
    name = free[roll(rng, 1, #free)]
  else
    for _ = 1, 100 do
      local k = roll(rng, 1, #INITIALS)
      local cand = L[roll(rng, 1, #L)] .. " " .. INITIALS:sub(k, k) .. "."
      if not used[cand] then
        name = cand
        break
      end
    end
    name = name or L[1]
  end
  used[name] = true
  return { last = name, nation = code }
end

