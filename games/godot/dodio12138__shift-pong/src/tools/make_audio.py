"""Makes SHIFT PONG's music and skill sounds from scratch: a little synth
(square, triangle, saw, FM, noise), two looping multitrack pieces and the
SHIFT sound effects. Everything is original, generated by this script.

usage: python3 tools/make_audio.py   (writes sounds/music/*.ogg, sounds/fx/*.wav)
"""
import os, subprocess, wave
import numpy as np

SR = 32000
ROOT = os.path.join(os.path.dirname(__file__), "..", "sounds")


def midi_hz(n):
    return 440.0 * 2.0 ** ((n - 69) / 12.0)


def square(f, t, duty=0.5):
    return np.where((f * t) % 1.0 < duty, 1.0, -1.0)


def triangle(f, t):
    return 4.0 * np.abs((f * t) % 1.0 - 0.5) - 1.0


def noise(n, rng, step=1):
    v = rng.uniform(-1.0, 1.0, n // step + 1)
    return np.repeat(v, step)[:n]


def env(n, a=0.005, d=0.0, s=1.0, r=0.03):
    """Attack / decay to sustain / release, in seconds, over n samples."""
    t = np.arange(n) / SR
    e = np.ones(n) * s
    if d > 0:
        e = np.where(t < a + d, 1.0 - (1.0 - s) * np.clip((t - a) / d, 0, 1), s)
    e = np.where(t < a, t / max(a, 1e-6), e)
    rel = n / SR - r
    e = np.where(t > rel, e * np.clip((n / SR - t) / max(r, 1e-6), 0, 1), e)
    return e


def note(wave_fn, n_midi, length, **kw):
    n = int(length * SR)
    t = np.arange(n) / SR
    return wave_fn(midi_hz(n_midi), t) * env(n, **kw)


def place(buf, sig, at):
    i = int(at * SR)
    j = min(len(buf), i + len(sig))
    if j > i:
        buf[i:j] += sig[: j - i]


def kick(length=0.18):
    n = int(length * SR)
    t = np.arange(n) / SR
    f = 50 + 120 * np.exp(-t * 30)
    ph = 2 * np.pi * np.cumsum(f) / SR
    return np.sin(ph) * np.exp(-t * 14)


def snare(rng, length=0.14):
    n = int(length * SR)
    t = np.arange(n) / SR
    return noise(n, rng, 2) * np.exp(-t * 22) * 0.8 + np.sin(2 * np.pi * 190 * t) * np.exp(-t * 30) * 0.3


def hat(rng, length=0.04):
    n = int(length * SR)
    t = np.arange(n) / SR
    return noise(n, rng, 1) * np.exp(-t * 90)


def write_wav(path, x):
    """Mono (1-D) or stereo (2 x n)."""
    x = np.clip(x, -1, 1)
    ch = 1 if x.ndim == 1 else 2
    data = x if ch == 1 else x.T.reshape(-1)
    with wave.open(path, "wb") as w:
        w.setnchannels(ch)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes((data * 32767).astype(np.int16).tobytes())


def write_ogg(path, x):
    tmp = path + ".tmp.wav"
    write_wav(tmp, x)
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", tmp, "-ac", "2", "-c:a", "vorbis", "-strict", "-2", "-q:a", "4", path], check=True)
    os.remove(tmp)


# ------------------------------------------------------------------ music
#
# A small multitrack arranger: each part is rendered into its own stereo bus,
# filtered, panned, then mixed with a little reverb. Softer voices than the
# effects: detuned-saw pads through a low-pass, an FM electric-piano arpeggio,
# a filtered pulse lead with echo, a triangle bass with a sine under it.

from scipy.signal import butter, lfilter


def lowpass(x, hz, order=2):
    b, a = butter(order, hz / (SR / 2), "low")
    return lfilter(b, a, x)


def highpass(x, hz, order=2):
    b, a = butter(order, hz / (SR / 2), "high")
    return lfilter(b, a, x)


def saw(f, t):
    return 2.0 * ((f * t) % 1.0) - 1.0


def pad_voice(n_midi, length, rng):
    """Three slightly detuned saws, slow attack and release."""
    m = int(length * SR)
    t = np.arange(m) / SR
    f = midi_hz(n_midi)
    x = sum(saw(f * (1.0 + d), t + rng.uniform(0, 1)) for d in (-0.006, 0.0, 0.007)) / 3.0
    return x * env(m, a=min(0.25, length * 0.3), r=min(0.5, length * 0.4))


def epiano(n_midi, length):
    """FM electric piano: a sine bent by a sine at twice its pitch, the bend dying away."""
    m = int(length * SR)
    t = np.arange(m) / SR
    f = midi_hz(n_midi)
    idx = 1.6 * np.exp(-t * 6.0)
    x = np.sin(2 * np.pi * f * t + idx * np.sin(2 * np.pi * 2 * f * t))
    return x * np.exp(-t * 3.2) * env(m, a=0.003, r=0.05)


def lead_voice(n_midi, length, duty=0.3):
    m = int(length * SR)
    t = np.arange(m) / SR
    f = midi_hz(n_midi) * (1.0 + 0.005 * np.sin(2 * np.pi * 5.2 * t) * np.clip((t - 0.12) / 0.2, 0, 1))
    ph = np.cumsum(f) / SR
    x = np.where(ph % 1.0 < duty, 1.0, -1.0) * 0.6 + np.sin(2 * np.pi * ph) * 0.6
    return x * env(m, a=0.02, d=0.2, s=0.75, r=0.06)


def bass_voice(n_midi, length):
    m = int(length * SR)
    t = np.arange(m) / SR
    f = midi_hz(n_midi)
    x = triangle(f, t) * 0.7 + np.sin(2 * np.pi * f * 0.5 * t) * 0.5
    return x * env(m, a=0.004, d=0.15, s=0.7, r=0.04)


def guitar(notes, length, mute=False):
    """A power chord on a distorted saw guitar, low-passed so it growls
    rather than fizzes; `mute` = palm-muted, short and dark."""
    m = int(length * SR)
    t = np.arange(m) / SR
    x = sum(saw(midi_hz(n) * (1.0 + d), t) for n in notes for d in (-0.003, 0.003)) / (2 * len(notes))
    x = np.tanh(x * 6.0)
    e = np.exp(-t * (18.0 if mute else 2.5)) * env(m, a=0.004, r=0.03)
    return x * e


def crash(rng, length=1.2):
    n = int(length * SR)
    t = np.arange(n) / SR
    return highpass(noise(n, rng, 1), 4000) * np.exp(-t * 3.5)


def reverb(x, wet=0.18):
    """Schroeder: four combs in parallel, two all-passes in series."""
    out = np.zeros_like(x)
    for d, g in ((1557, 0.80), (1617, 0.79), (1491, 0.78), (1422, 0.77)):
        d = int(d * SR / 44100)
        a = np.zeros(d + 1)
        a[0], a[d] = 1.0, -g
        out += lfilter([1.0], a, x)
    for d, g in ((225, 0.5), (556, 0.5)):
        d = int(d * SR / 44100)
        b = np.zeros(d + 1)
        b[0], b[d] = -g, 1.0
        a = np.zeros(d + 1)
        a[0], a[d] = 1.0, -g
        out = lfilter(b, a, out)
    return x * (1.0 - wet) + lowpass(out, 5000) * wet * 0.25


def echo(x, secs, fb=0.35, mix=0.3):
    d = int(secs * SR)
    a = np.zeros(d + 1)
    a[0], a[d] = 1.0, -fb
    return x + lfilter([1.0], a, np.concatenate([np.zeros(d), x[:-d]])) * mix


class Mix:
    """Stereo buses by name; each part adds mono into a bus with a pan."""

    def __init__(self, secs):
        self.n = int(secs * SR)
        self.buses = {}

    def add(self, bus, sig, at, pan=0.0, gain=1.0):
        b = self.buses.setdefault(bus, np.zeros((2, self.n)))
        i = int(at * SR)
        j = min(self.n, i + len(sig))
        if j <= i:
            return
        l = np.cos((pan + 1) * np.pi / 4) * gain
        r = np.sin((pan + 1) * np.pi / 4) * gain
        b[0, i:j] += sig[: j - i] * l
        b[1, i:j] += sig[: j - i] * r


# chords: (bass root, pad voicing)
CH = {
    "Am9": (45, [57, 60, 64, 67, 71]), "Am7": (45, [57, 60, 64, 67]), "Am": (45, [57, 60, 64, 69]),
    "Fmaj7": (41, [57, 60, 64, 65]), "F": (41, [57, 60, 65, 69]), "Cadd9": (48, [55, 60, 62, 64]),
    "C": (48, [55, 60, 64, 67]), "G6": (43, [55, 59, 62, 64]), "G": (43, [55, 59, 62, 67]),
    "Dm7": (50, [57, 60, 62, 65]), "Em7": (40, [55, 59, 62, 64]), "E7": (40, [56, 59, 62, 64]),
    "E": (40, [56, 59, 64, 68]),
}


def arrange(bpm, bars, chords, lead, counter, drums, arp_rate, seed, guitar_on=False):
    rng = np.random.default_rng(seed)
    beat = 60.0 / bpm
    bar = beat * 4
    total = bars * bar
    tail = 3.0
    mx = Mix(total + tail)
    for b in range(bars):
        name = chords[b % len(chords)]
        root, voicing = CH[name]
        t0 = b * bar
        # pad: the whole bar, notes spread across the stereo field
        for k, n in enumerate(voicing):
            mx.add("pad", pad_voice(n, bar * 1.02, rng) * 0.22, t0, pan=-0.6 + 1.2 * k / max(len(voicing) - 1, 1))
        # bass: root on the beat, octave answer on the off-beats in the busier tracks
        if drums == "rock":    # driving eighths on the root, an octave jump on the last
            steps = [(k * 0.5, 0.45) for k in range(8)]
        elif drums in ("drive", "softrock"):
            steps = [(0, 1.5), (1.5, 0.5), (2, 1.5), (3.5, 0.5)]
        else:
            steps = [(0, 2.5), (2.5, 1.5)]
        for at, ln in steps:
            n = root - 12 if (drums != "rock" and at % 1 == 0) or (drums == "rock" and at != 3.5) else root
            mx.add("bass", bass_voice(n, ln * beat * 0.95) * 0.5, t0 + at * beat)
        # electric-piano arpeggio, up and down the chord, bouncing left and right
        tones = voicing + [voicing[1] + 12, voicing[2] + 12]
        order = tones + tones[-2:0:-1]
        step = beat / arp_rate
        for k in range(int(4 * arp_rate)):
            n = order[k % len(order)] + 12
            mx.add("arp", epiano(n, step * 2.5) * 0.18, t0 + k * step, pan=-0.45 if k % 2 else 0.45)
        # rock guitar: power chords, palm-muted eighths with an open hit on the one
        if guitar_on:
            pc = [root, root + 7, root + 12]
            for k in range(8):
                at = t0 + k * beat / 2
                open_hit = k == 0 or (k == 6 and b % 2 == 1)
                mx.add("guitar", guitar(pc, beat * (1.5 if open_hit else 0.45), mute=not open_hit) * 0.5, at,
                       pan=-0.5 if k % 2 == 0 else 0.5)
        # drums
        fill = b % 4 == 3
        for k in range(16):
            at = t0 + k * beat / 4
            if drums == "rock":
                if k == 0 and b % 8 == 0:
                    mx.add("drums", crash(rng) * 0.12, at, pan=-0.4)
                if k in (0, 6, 8) or (k == 10 and b % 2):
                    mx.add("drums", kick(0.25) * 0.8, at)
                if k in (4, 12) and not (fill and k == 12):
                    mx.add("drums", highpass(snare(rng, 0.2), 250) * 0.42, at, pan=0.05)
                if fill and k >= 12:   # a snare fill into the next phrase
                    mx.add("drums", highpass(snare(rng, 0.1), 300) * (0.25 + 0.05 * (k - 12)), at, pan=-0.3 + 0.2 * (k - 12))
                if k % 2 == 0 and not (fill and k >= 12):
                    mx.add("drums", highpass(hat(rng, 0.03), 7000) * (0.11 if k % 4 == 0 else 0.07), at, pan=0.3)
                continue
            if drums == "softrock":
                if k in (0, 10):
                    mx.add("drums", kick(0.25) * 0.5, at)
                if k in (4, 12):
                    mx.add("drums", lowpass(highpass(snare(rng, 0.12), 400), 4000) * 0.2, at, pan=0.05)
                if k % 2 == 0:
                    mx.add("drums", highpass(hat(rng, 0.03), 6000) * 0.05, at, pan=0.3)
                continue
            if drums == "drive":
                if k in (0, 8) or (k == 10 and b % 2):
                    mx.add("drums", kick(0.25) * 0.7, at)
                if k in (4, 12):
                    mx.add("drums", highpass(snare(rng, 0.18), 300) * 0.32, at, pan=0.05)
                if k % 2 == 0:
                    mx.add("drums", highpass(hat(rng, 0.03), 7000) * (0.12 if k % 4 else 0.07), at, pan=0.3)
                if k % 4 == 2 and b % 4 == 3:
                    mx.add("drums", highpass(hat(rng, 0.12), 6000) * 0.08, at, pan=-0.3)   # open hat into the next phrase
            else:
                if k == 0:
                    mx.add("drums", kick(0.25) * 0.45, at)
                if k == 8:
                    mx.add("drums", highpass(snare(rng, 0.08), 1200) * 0.12, at, pan=0.1)   # a soft rim
                if k % 2 == 1:
                    mx.add("drums", highpass(hat(rng, 0.05), 5000) * 0.05, at, pan=-0.25)   # shaker
    # lead and counter-melody: (midi or None, sixteenths)
    for part, notes, pan, gain in (("lead", lead, 0.0, 0.2), ("counter", counter, -0.25, 0.12)):
        at = 0.0
        six = beat / 4
        for n, d in notes:
            if n is not None:
                v = lead_voice(n, d * six * 0.97) if part == "lead" else bass_voice(n, d * six * 0.97) * 0.8
                mx.add(part, v * gain / 0.2, at, pan=pan)
            at += d * six
    # per-bus colour, then the mix
    cut = {"pad": 1800, "arp": 4500, "lead": 3200, "counter": 2500, "bass": 900, "drums": 12000, "guitar": 2600}
    out = np.zeros((2, mx.n))
    for name, bus in mx.buses.items():
        for c in range(2):
            x = lowpass(bus[c], cut[name])
            if name == "lead":
                x = echo(x, beat * 0.75 if c == 0 else beat * 0.5, 0.3, 0.28)   # dotted echo on the left, eighths on the right
            out[c] += x
    for c in range(2):
        out[c] = reverb(out[c], 0.22)
    # fold the tail back onto the start so the loop is seamless
    L = int(total * SR)
    out[:, : mx.n - L] += out[:, L:]
    out = out[:, :L]
    out = out / (np.max(np.abs(out)) + 1e-9)
    out = np.tanh(out * 1.1) / np.tanh(1.1)   # a gentle glue on the peaks
    rms = np.sqrt((out ** 2).mean())
    return out * min(0.2 / rms, 0.89 / np.max(np.abs(out)))   # about -14 dB RMS, peaks well clear


